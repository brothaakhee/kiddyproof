import Foundation
import CryptoKit

// Licensing — pure, unit-testable logic. The app ships with a free trial;
// after it lapses, arming kid mode requires a license key.
//
// Keys are OFFLINE-VERIFIABLE: `KIDDY.<payload>.<signature>` where payload is
// base64url JSON ({"e":email,"d":issue-date,"p":plan}) and the signature is
// Ed25519 over the raw payload bytes. The private key never ships — it lives
// with the seller (Scripts/make_license.swift); the app embeds only the
// public key. No server, no phone-home, works in an offline household.
public enum License {

    // THE PAYWALL SWITCH. 0 = hard paywall: kid mode needs a license from the
    // very first launch. Any positive number restores a free trial of that many
    // days. Nothing else in the app needs to change to flip between the two —
    // `entitlement` falls through to .expired whenever no days remain.
    public static let trialDays = 0

    // Whether this build offers a trial at all. Derived, never set by hand, so
    // UI copy can't drift out of sync with the switch above.
    public static var offersTrial: Bool { trialDays > 0 }

    // Ed25519 public key (raw 32 bytes, base64). The matching private key is
    // generated by `swift Scripts/make_license.swift generate-keys` and must
    // NEVER be committed.
    public static let publicKeyB64 = "KD85xXx3dhShA3IZX1N5KgQJYxYZIWL65WNY0fFmliU="

    public struct Payload: Codable, Equatable {
        public let e: String      // purchaser email
        public let d: String      // issue date, ISO yyyy-MM-dd
        public let p: String      // plan ("pro")
        public init(e: String, d: String, p: String) {
            self.e = e
            self.d = d
            self.p = p
        }
    }

    public enum Entitlement: Equatable {
        case licensed(email: String)
        case trial(daysLeft: Int)
        case expired
    }

    // MARK: Key verification

    public static func verify(key: String, publicKeyB64: String = publicKeyB64) -> Payload? {
        let trimmed = key.trimmingCharacters(in: .whitespacesAndNewlines)
        let parts = trimmed.split(separator: ".")
        guard parts.count == 3, parts[0] == "KIDDY",
              let payloadData = base64urlDecode(String(parts[1])),
              let sigData = base64urlDecode(String(parts[2])),
              let pubData = Data(base64Encoded: publicKeyB64),
              let pub = try? Curve25519.Signing.PublicKey(rawRepresentation: pubData),
              pub.isValidSignature(sigData, for: payloadData),
              let payload = try? JSONDecoder().decode(Payload.self, from: payloadData)
        else { return nil }
        return payload
    }

    // MARK: Trial math

    // Whole days of trial remaining; 0 means lapsed. The first-launch date is
    // clamped so a forward-set clock can't extend the trial.
    public static func trialDaysLeft(firstLaunch: Date, now: Date = Date(),
                                     trialDays: Int = trialDays) -> Int {
        let start = min(firstLaunch, now)
        let elapsed = now.timeIntervalSince(start)
        let used = Int(floor(elapsed / 86_400))
        return max(0, trialDays - used)
    }

    public static func entitlement(licenseKey: String?, firstLaunch: Date,
                                   now: Date = Date(),
                                   publicKeyB64: String = publicKeyB64,
                                   trialDays: Int = trialDays) -> Entitlement {
        if let key = licenseKey, let payload = verify(key: key, publicKeyB64: publicKeyB64) {
            return .licensed(email: payload.e)
        }
        // trialDays == 0 makes this .expired on the very first launch, which is
        // exactly the hard-paywall behaviour; no separate code path needed.
        let left = trialDaysLeft(firstLaunch: firstLaunch, now: now, trialDays: trialDays)
        return left > 0 ? .trial(daysLeft: left) : .expired
    }

    // MARK: base64url

    public static func base64urlDecode(_ s: String) -> Data? {
        var b = s.replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
        while b.count % 4 != 0 { b += "=" }
        return Data(base64Encoded: b)
    }

    public static func base64urlEncode(_ d: Data) -> String {
        d.base64EncodedString()
            .replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_")
            .replacingOccurrences(of: "=", with: "")
    }
}
